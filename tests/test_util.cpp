Bytes expected() {
    Bytes b;
    for (int i = 0; i < 20; ++i) {
        putText(b, "Nagus nagus nagus! ");
    }
    for (int i = 0; i < 256; ++i) {
        b.push_back(static_cast<std::uint8_t>(i));
    }
    return b;
}

